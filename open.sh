#!/usr/bin/env bash
# ============================================================
# 一键打开说明：启动服务 → 打印访问地址
# 用法：bash open.sh
# ============================================================
set -u

BASE="$(cd "$(dirname "$0")" && pwd)"

echo "============================================================"
echo " 智慧医疗平台 · 快速打开"
echo "============================================================"

# 1. 若服务未启动则拉起
if ! (ss -tln 2>/dev/null | grep -q ':5173 '); then
  echo "[1/3] 服务未运行，正在启动 ..."
  bash "$BASE/start.sh"
else
  echo "[1/3] 服务已在运行"
fi

# 2. 确认前端端口
echo "[2/3] 确认前端端口："
ss -tln 2>/dev/null | grep -E ':5173' || echo "  (未检测到 5173)"

# 3. 打印访问地址（本机 + 局域网）
LAN_IP=$(hostname -I 2>/dev/null | awk '{print $1}')
echo "[3/3] 访问地址："
echo "  本机:    http://localhost:5173"
[ -n "$LAN_IP" ] && echo "  局域网:  http://$LAN_IP:5173"
echo
echo "服务端口：Flask 分析 5000 / core 8000 / drg 8001 / agent 5001 / 前端 5173"
